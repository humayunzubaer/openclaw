_HASANTA = "\u09CD"          # ্
_RA = "র"
_YA = "য"

# ই-কার ও ঐ-কার — সম্মুখে বসে
_PRE_VOWELS = {"ি": "w", "ে": "‡", "ৈ": "‰"}

# ও-কার ও ঔ-কার — দুই দিকে ভাঙে
_SPLIT_VOWELS = {
    "ো": ("‡", "v"),      # ে + া
    "ৌ": ("‡", "Š"),      # ে + ৗ
}

_BN_LETTER = r"[\u0985-\u09B9\u09CE\u09DC-\u09DF]"

# 'য়' যুক্ত বিশেষ রূপ
CONJUNCT_MAP_EXTRA = {
    "য়": "q", "ড়": "o", "ঢ়": "p",
    "ওয়": "Iq", "য়া": "qv", "য়ে": "‡q", "য়ু": "qy",
}


def _apply_conjuncts(text: str) -> str:
    """যুক্তাক্ষর প্রতিস্থাপন — দীর্ঘতম আগে"""
    for k in sorted(CONJUNCT_MAP.keys(), key=len, reverse=True):
        if k in text:
            text = text.replace(k, "\x00" + CONJUNCT_MAP[k] + "\x00")
    return text


# র-ফলাযুক্ত বিশেষ রূপ — সাধারণ 'ª' নয়
RA_PHALA_SPECIAL: dict[str, str] = {
    "প্র": "cÖ", "ব্র": "eª", "ক্র": "µ", "গ্র": "MÖ", "ত্র": "Î",
    "দ্র": "`ª", "ধ্র": "aª", "ন্র": "bª", "ফ্র": "d«", "ভ্র": "å",
    "ম্র": "gª", "শ্র": "kª", "স্র": "mª", "হ্র": "ü", "জ্র": "Rª",
    "ট্র": "Uª", "ড্র": "Wª", "থ্র": "_ª", "চ্র": "Pª", "ক্ষ্র": "¶ª",
}


def _handle_ref_and_phala(text: str) -> str:
    """
    রেফ ও ফলা প্রক্রিয়াকরণ।

    রেফ   : র্ + ব্যঞ্জন   → ব্যঞ্জন + র্‌চিহ্ন ("©")
    র-ফলা : ব্যঞ্জন + ্র   → ব্যঞ্জন + "ª"
    য-ফলা : ব্যঞ্জন + ্য   → ব্যঞ্জন + "¨"
    """
    # রেফ — র্ক → ক©
    text = re.sub(
        rf"{_RA}{_HASANTA}({_BN_LETTER})",
        lambda m: m.group(1) + "\x01",     # \x01 = রেফ চিহ্ন (পরে ©)
        text,
    )
    # র-ফলা — বিশেষ রূপ আগে (প্র → cÖ)
    for k in sorted(RA_PHALA_SPECIAL.keys(), key=len, reverse=True):
        if k in text:
            text = text.replace(k, "\x00" + RA_PHALA_SPECIAL[k] + "\x00")
    # অবশিষ্ট সাধারণ র-ফলা
    text = re.sub(
        rf"({_BN_LETTER}){_HASANTA}{_RA}",
        lambda m: m.group(1) + "\x02",
        text,
    )
    # য-ফলা — ক্য → ক¨  (য়/ড়/ঢ় নহে, কেবল খাঁটি 'য')
    text = re.sub(
        rf"({_BN_LETTER}){_HASANTA}{_YA}(?![\u09BC])",
        lambda m: m.group(1) + "\x03",
        text,
    )
    return text


def _reorder_vowels(text: str) -> str:
    """
    ই-কার/এ-কার/ঐ-কার সম্মুখে স্থানান্তর এবং ও-কার/ঔ-কার বিভাজন।

    কি → wK  |  কো → ‡Kv  |  কৌ → ‡KŠ
    """
    out: list[str] = []
    i = 0
    n = len(text)

    while i < n:
        ch = text[i]

        # --- ও-কার / ঔ-কার (দুই দিকে) ---
        if ch in _SPLIT_VOWELS:
            pre, post = _SPLIT_VOWELS[ch]
            # পূর্ববর্তী ব্যঞ্জনগুচ্ছ খুঁজে বের করো
            j = len(out) - 1
            while j >= 0 and out[j] in ("\x01", "\x02", "\x03"):
                j -= 1
            if j >= 0:
                out.insert(j, pre)
                out.append(post)
            else:
                out.append(pre + post)
            i += 1
            continue

        # --- সম্মুখগামী কার ---
        if ch in _PRE_VOWELS:
            j = len(out) - 1
            while j >= 0 and out[j] in ("\x01", "\x02", "\x03"):
                j -= 1
            if j >= 0:
                out.insert(j, ch)
            else:
                out.append(ch)
            i += 1
            continue

        out.append(ch)
        i += 1

    return "".join(out)


def unicode_to_bijoy(text: str | None) -> str:
    """
    ★ ইউনিকোড বাংলা → বিজয় (SutonnyMJ) সংকেত

    উদাহরণ: "প্রাপ্যতা" → "cÖvc¨Zv"
    """
    if not text:
        return ""

    s = unicodedata.normalize("NFC", str(text))
    # nukta-যুক্ত অক্ষর একীভূত করো (য + ় → য়)
    for base, combined in (("\u09AF\u09BC", "\u09DF"),   # য় 
                           ("\u09A1\u09BC", "\u09DC"),   # ড়
                           ("\u09A2\u09BC", "\u09DD")):  # ঢ়
        s = s.replace(base, combined)

    # ইংরেজি/সংখ্যা-মাত্র অংশ অপরিবর্তিত রাখিতে খণ্ডে ভাগ করো
    parts = re.split(r"([\u0980-\u09FF\u0964\u0965]+)", s)
    result: list[str] = []

    for part in parts:
        if not part:
            continue
        if not re.search(r"[\u0980-\u09FF\u0964\u0965]", part):
            result.append(part)       # ইংরেজি/সংখ্যা/চিহ্ন
            continue

        t = part
        t = _apply_conjuncts(t)          # দীর্ঘ যুক্তাক্ষর আগে (ন্ত্র, স্ত্র)
        t = _handle_ref_and_phala(t)     # তারপর রেফ ও ফলা
        t = _reorder_vowels(t)

        # একক অক্ষর প্রতিস্থাপন
        buf: list[str] = []
        for ch in t:
            if ch == "\x00":
                continue                      # যুক্তাক্ষরের সীমানা
            elif ch == "\x01":
                buf.append("©")               # রেফ
            elif ch == "\x02":
                buf.append("ª")               # র-ফলা
            elif ch == "\x03":
                buf.append("¨")               # য-ফলা
            elif ch in SINGLE_MAP:
                buf.append(SINGLE_MAP[ch])
            else:
                buf.append(ch)
        result.append("".join(buf))

    return "".join(result)


