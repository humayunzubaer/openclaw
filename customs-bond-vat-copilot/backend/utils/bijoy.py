FONT_BANGLA_LEGACY = "SutonnyMJ"     # বিজয় — রূপান্তর আবশ্যক
FONT_BANGLA_UNICODE = "Nikosh"       # ইউনিকোড
FONT_ENGLISH = "Times New Roman"


def is_bangla(text: str | None) -> bool:
    """লেখায় বাংলা অক্ষর আছে কিনা"""
    return bool(text) and bool(re.search(r"[\u0980-\u09FF]", str(text)))


def split_by_script(text: str | None) -> list[tuple[str, str]]:
    """
    লেখাকে বাংলা ও ইংরেজি খণ্ডে ভাগ করো — প্রতিটির জন্য উপযুক্ত ফন্ট।

    ফেরত: [(খণ্ড, ফন্টের নাম), ...]

    উদাহরণ: "HS কোড 5208.11.00 এর বিপরীতে"
        → [("HS ", "Times New Roman"),
           ("কোড ", "SutonnyMJ"),
           ("5208.11.00 ", "Times New Roman"), ...]
    """
    if not text:
        return []

    s = unicodedata.normalize("NFC", str(text))
    for base, combined in (("\u09AF\u09BC", "\u09DF"),
                           ("\u09A1\u09BC", "\u09DC"),
                           ("\u09A2\u09BC", "\u09DD")):
        s = s.replace(base, combined)
    out: list[tuple[str, str]] = []
    buf, cur_font = [], None

    for ch in s:
        # বাংলা সংখ্যা ও টাকার চিহ্ন → ইংরেজি রানে (সংখ্যা অপরিবর্তিত)
        if ch in "০১২৩৪৫৬৭৮৯৳" or ch.isdigit():
            font = FONT_ENGLISH
        elif "\u0980" <= ch <= "\u09FF" or ch in "\u0964\u0965":
            font = FONT_BANGLA_LEGACY
        elif ch.isspace():
            font = cur_font or FONT_ENGLISH   # স্পেস পূর্বের ফন্টেই
        else:
            font = FONT_ENGLISH

        if font != cur_font and buf:
            out.append(("".join(buf), cur_font))
            buf = []
        cur_font = font
        buf.append(ch)

    if buf:
        out.append(("".join(buf), cur_font))
    return out


def to_display_runs(text: str | None) -> list[tuple[str, str]]:
    """
    ★ প্রতিবেদনে বসাইবার জন্য চূড়ান্ত রূপ।

    বাংলা খণ্ড বিজয়ে রূপান্তরিত হইয়া SutonnyMJ ফন্টে,
    ইংরেজি খণ্ড অপরিবর্তিত Times New Roman ফন্টে।
    """
    runs = split_by_script(text)
    out: list[tuple[str, str]] = []
    for chunk, font in runs:
        if font == FONT_BANGLA_LEGACY:
            out.append((unicode_to_bijoy(chunk), font))
        else:
            out.append((chunk, font))
    return out


