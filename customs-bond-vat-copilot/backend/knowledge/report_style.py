def to_cholit(text: str | None, protect_quotes: bool = True) -> str:
    """
    সাধু ভাষার লেখাকে প্রমিত চলিত ভাষায় রূপান্তর করে।

    protect_quotes = True হলে উদ্ধৃতিচিহ্নের ("…" বা “…”) ভিতরের অংশ
    অপরিবর্তিত থাকে — কারণ আইনের হুবহু উদ্ধৃতি বদলানো যাবে না।
    """
    if not text:
        return ""
    import re as _re
    s = str(text)

    if protect_quotes:
        kept: list[str] = []

        def _hold(m):
            kept.append(m.group(0))
            return f"\x00{len(kept)-1}\x00"

        s = _re.sub(r'[“"”][^“"”]{0,600}[“"”]', _hold, s)

    for a, b in sorted(SADHU_TO_CHOLIT.items(), key=lambda x: -len(x[0])):
        s = s.replace(a, b)

    if protect_quotes:
        for i, q in enumerate(kept):
            s = s.replace(f"\x00{i}\x00", q)
    return s


