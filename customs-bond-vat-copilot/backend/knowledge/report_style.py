@dataclass
class OpinionItem:
    """প্রস্তাব ও মতামতের একটি দফা"""
    label: str              # ক), খ), গ)…
    text: str
    para_ref: str = ""
    amount: float = 0.0
    kind: str = "general"


def build_opinion(
    company: str, period_from: str, period_to: str,
    findings: list[dict] | None = None,
    entitlement_para: str = "",
    start_para: str = "০২", end_para: str = "৩৯",
) -> list[OpinionItem]:
    """
    বিশ্লেষণের ফলাফল হইতে 'প্রস্তাব ও মতামত' অনুচ্ছেদ প্রস্তুত করো।

    findings: [{"kind": "excess_import", "para": "৩৬", "quantity": 141.291,
                "unit": "মেঃ টন", "amount": 1542936.0, ...}, ...]
    """
    items: list[OpinionItem] = []
    labels = ["ক", "খ", "গ", "ঘ", "ঙ", "চ", "ছ", "জ", "ঝ", "ঞ"]
    i = 0

    def _next() -> str:
        nonlocal i
        lb = labels[i] if i < len(labels) else f"({i+1})"
        i += 1
        return f"{lb})"

    # ১) নিরীক্ষা অনুমোদন
    items.append(OpinionItem(
        label=_next(), kind="audit_approval",
        text=OPINION_TEMPLATES["audit_approval"].format(
            company=company, period_from=period_from, period_to=period_to
        ),
    ))

    # ২) প্রাপ্যতা অনুমোদন
    if entitlement_para:
        items.append(OpinionItem(
            label=_next(), kind="entitlement_approval", para_ref=entitlement_para,
            text=OPINION_TEMPLATES["entitlement_approval"].format(
                para=entitlement_para
            ),
        ))

    # ৩) আপত্তিভিত্তিক দাবি
    for f in (findings or []):
        kind = f.get("kind", "")
        tpl = OPINION_TEMPLATES.get(kind)
        if not tpl:
            continue
        data = dict(f)
        amt = float(f.get("amount") or 0)
        data["amount"] = _indian_group(amt) + " টাকা"
        w = number_to_bangla_words(amt, with_paisa=True)
        data["amount_words"] = w if "টাকা" in w else w + " টাকা"
        try:
            items.append(OpinionItem(
                label=_next(), kind=kind, para_ref=str(f.get("para", "")),
                amount=amt, text=tpl.format(**data),
            ))
        except KeyError as e:
            items.append(OpinionItem(
                label=_next(), kind=kind,
                text=f"[ছাঁচ পূরণ করা যায় নাই — অনুপস্থিত তথ্য: {e}]",
            ))

    return items


def render_opinion(
    items: list[OpinionItem], start_para: str = "০২", end_para: str = "৩৯"
) -> str:
    """প্রস্তাব ও মতামত অনুচ্ছেদ সম্পূর্ণ লেখা"""
    lines = [
        "প্রস্তাব ও মতামতঃ",
        "",
        OPINION_OPENING.format(from_para=start_para, to_para=end_para),
        "",
    ]
    for it in items:
        lines.append(f"{it.label}\t{it.text}")
        lines.append("")
    lines.append(OPINION_CLOSING)
    return "\n".join(lines)


