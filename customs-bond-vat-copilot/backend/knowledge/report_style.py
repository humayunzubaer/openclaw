def _paisa_words(amount: float) -> str:
    """দশমিক অংশ কথায় — '.৩৪' → 'টাকা চৌত্রিশ পয়সা'"""
    paisa = int(round((abs(float(amount)) % 1) * 100))
    return f" টাকা {_ONES[paisa]} পয়সা" if paisa else ""


def number_to_bangla_words(amount: float, with_paisa: bool = False) -> str:
    """
    সংখ্যাকে বাংলা কথায় রূপান্তর — ভারতীয় উপমহাদেশীয় রীতিতে
    (কোটি / লক্ষ / হাজার / শত)।

    ১৫৪২৯৩৬ → "পনের লক্ষ বিয়াল্লিশ হাজার নয়শত ছত্রিশ"
    """
    try:
        n = int(round(float(amount)))
    except (TypeError, ValueError):
        return ""
    if n == 0:
        return "শূন্য"

    neg = n < 0
    n = abs(n)
    parts: list[str] = []

    for div, label in ((10_000_000, "কোটি"), (100_000, "লক্ষ"), (1_000, "হাজার")):
        if n >= div:
            q, n = divmod(n, div)
            parts.append(f"{number_to_bangla_words(q)} {label}"
                         if q > 99 else f"{_ONES[q]} {label}")

    if n >= 100:
        q, n = divmod(n, 100)
        parts.append(f"{_ONES[q]}শত")
    if n > 0:
        parts.append(_ONES[n])

    out = " ".join(p.strip() for p in parts if p.strip())
    if with_paisa:
        out += _paisa_words(amount)
    return ("ঋণাত্মক " + out) if neg else out


def format_taka(amount: float) -> str:
    """
    দাপ্তরিক রীতিতে টাকার অঙ্ক।
    ১৫৪২৯৩৬ → "১৫,৪২,৯৩৬.০০ (পনের লক্ষ বিয়াল্লিশ হাজার নয়শত ছত্রিশ) টাকা"
    """
    return (f"{_indian_group(amount)} টাকা "
            f"({number_to_bangla_words(amount, with_paisa=True)})")


def _to_bangla_digits(s: str) -> str:
    return s.translate(str.maketrans("0123456789", "০১২৩৪৫৬৭৮৯"))


def _indian_group(amount: float, decimals: int = 2) -> str:
    """
    ভারতীয় উপমহাদেশীয় রীতিতে অঙ্ক বিভাজন —
    ১৫৪২৯৩৬ → "১৫,৪২,৯৩৬" (নয়: "১,৫৪২,৯৩৬")
    """
    neg = amount < 0
    whole = int(abs(amount))
    frac = abs(amount) - whole
    s_ = str(whole)
    if len(s_) > 3:
        head, tail = s_[:-3], s_[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s_ = ",".join(parts) + "," + tail
    if decimals:
        s_ += f".{int(round(frac * 10 ** decimals)):0{decimals}d}"
    return ("-" if neg else "") + _to_bangla_digits(s_)


