#   নিরপেক্ষ   : দুই ফন্টেই একই দেখায় — চলতি রানের সহিত জুড়িয়া যায়
#   ইংরেজি-রান : বিজয়ে ইহারা বাংলা গ্লিফ; তাই ইংরেজি ফন্টে যাইতেই হইবে
#
# ★ যাচাইকৃত: সমস্ত ASCII অক্ষর (A-Z, a-z) ও অঙ্ক (0-9) বিজয়ে বাংলা
#   গ্লিফ। '~' = ূ, '_' = থ, '`' = দ, '&' = ্, '^' = ্ব, '|' = ।
#   '—' = ্ত, '…' = ৃ — ইহারাও ইংরেজি রানে থাকিবে।

BANGLA_CP = re.compile(r"[\u0980-\u09FF\u200c\u200d\u0964\u0965‘’“”]")

# দুই ফন্টে একই দেখায় — অকারণে রান ভাঙে না
NEUTRAL = set(" \t\n\r,.()-/:;?!%+=*#$<>[]{}\"'")


def is_bangla(ch: str) -> bool:
    return bool(BANGLA_CP.match(ch))


def _kind_of(ch: str) -> str:
    if is_bangla(ch):
        return "bn"
    if ch in NEUTRAL:
        return "neutral"
    return "other"


def split_runs(text: str) -> list[tuple[str, str]]:
    """
    লেখাকে ('bn', খণ্ড) ও ('other', খণ্ড) — এই দুই শ্রেণিতে ভাগ করে।

    ★ বিজয় ফন্টে অ-বাংলা খণ্ড কখনো রাখিবেন না; উহা ইংরেজি ফন্টে যাইবে।
      কারণ 'K' বিজয়ে 'ক' — ইংরেজি লেখা বাংলা আবর্জনা হইয়া যায়।

    নিরপেক্ষ চিহ্ন (স্পেস, কমা, দাঁড়ির বাহিরের যতি) চলতি রানের সহিত
    জুড়িয়া যায়, যাহাতে অকারণে অসংখ্য ছোট রান তৈরি না হয়।
    """
    if not text:
        return []

    out: list[tuple[str, str]] = []
    buf, kind = "", None
    pending = ""              # রান শুরুর আগে জমা নিরপেক্ষ চিহ্ন

    for ch in text:
        k = _kind_of(ch)

        if k == "neutral":
            if kind is None:
                pending += ch
            else:
                buf += ch
            continue

        if kind is None:
            kind, buf = k, pending + ch
            pending = ""
        elif k == kind:
            buf += ch
        else:
            # রান বদলাইতেছে — শেষের নিরপেক্ষ চিহ্নগুলি পরের রানে যাক
            tail = ""
            while buf and _kind_of(buf[-1]) == "neutral":
                tail = buf[-1] + tail
                buf = buf[:-1]
            if buf:
                out.append((kind, buf))
            kind, buf = k, tail + ch

    if buf or pending:
        out.append((kind or "other", (buf or "") + ("" if buf else pending)))
    if pending and buf:
        pass
    return [(k, v) for k, v in out if v]


