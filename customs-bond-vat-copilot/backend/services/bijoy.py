def _tokenize(text: str) -> list:
    """
    বাংলা লেখাকে ক্লাস্টারে ভাঙে। যাহা ক্লাস্টার নহে (দাঁড়ি, স্পেস,
    যতিচিহ্ন) তাহা কাঁচা str হিসাবে ফেরত যায়।
    """
    out: list = []
    i, n = 0, len(text)

    while i < n:
        ch = text[i]

        # ---- ক্লাস্টার শুরু হয় ব্যঞ্জন বা স্বর দিয়া ----
        if ch not in CONSONANTS and ch not in VOWELS:
            out.append(ch)
            i += 1
            continue

        cl = _Cluster()

        # ---- রেফ: র + ্ + ব্যঞ্জন ----
        if (ch == RA and i + 2 < n and text[i + 1] == HASANTA
                and text[i + 2] in CONSONANTS):
            cl.reph = True
            i += 2
            ch = text[i]

        # ---- মূল + যুক্তাক্ষর শৃঙ্খল ----
        cl.body = ch
        i += 1
        while (i + 1 < n and text[i] == HASANTA
               and text[i + 1] in CONSONANTS):
            cl.body += HASANTA + text[i + 1]
            i += 2

        # ---- ঝুলন্ত হসন্ত (শব্দান্তে) ----
        if i < n and text[i] == HASANTA:
            nxt = text[i + 1] if i + 1 < n else ""
            if nxt not in CONSONANTS:
                cl.body += HASANTA
                i += 1

        # ---- কার ----
        if i < n:
            c = text[i]
            if c in COMPOSED_KARS:                 # ো ৌ
                pre, post = COMPOSED_KARS[c]
                cl.pre_kar, cl.post_kar = pre, post
                i += 1
            elif c in PRE_KARS:
                cl.pre_kar = c
                i += 1
            elif c in POST_KARS:
                cl.post_kar = c
                i += 1

        # ---- চিহ্ন (ঁ ং ঃ) ----
        while i < n and text[i] in SIGNS:
            cl.signs += text[i]
            i += 1

        out.append(cl)

    return out


def _map_body(body: str, post_kar: str) -> tuple[str, str]:
    """
    ক্লাস্টারের মূল অংশকে বিজয়-গ্লিফে বদলায়।

    কিছু যুক্তরূপ কার-সমেত একক গ্লিফ (গু=¸, শু=ï, হু=û, হৃ=ü, রু=i“,
    ন্তু=š‘)। তাই আগে কার-সমেত মিল খুঁজি; পাইলে কারটি এখানেই ফুরায়।
    """
    if post_kar:
        combined = body + post_kar
        if combined in UNICODE_TO_BIJOY:
            return UNICODE_TO_BIJOY[combined], ""       # কার শোষিত

    # দীর্ঘতম-মিল: পুরা মূল, নয়তো ভাঙিয়া
    if body in UNICODE_TO_BIJOY:
        return UNICODE_TO_BIJOY[body], post_kar

    out, i, n = "", 0, len(body)
    while i < n:
        # ১) দীর্ঘতম যুক্তরূপ
        for ln in range(min(7, n - i), 0, -1):
            piece = body[i:i + ln]
            if piece in UNICODE_TO_BIJOY:
                out += UNICODE_TO_BIJOY[piece]
                i += ln
                break
        else:
            # ২) হসন্ত-শৃঙ্খল: পরের অংশ "্ব"-জাতীয় সংযুক্ত-রূপে বসে
            nxt = body[i:i + 2]
            if body[i] == HASANTA and nxt in UNICODE_TO_BIJOY:
                out += UNICODE_TO_BIJOY[nxt]
                i += 2
            else:
                out += body[i]      # অজানা — অপরিবর্তিত
                i += 1
    return out, post_kar


def _render(cl: _Cluster) -> str:
    """
    বিজয়ের দৃশ্য-ক্রমে সাজায় —

        [আগের কার]  [মূল]  [রেফ]  [পরের কার]  [চিহ্ন]

    উদাহরণ: কর্তৃ → K  Z ©  …   (ত-এর পর রেফ, তারপর ৃ-কার)
             নিরীক্ষা → w b  i x  ¶ v
    """
    body, post_kar = _map_body(cl.body, cl.post_kar)

    parts = []
    if cl.pre_kar:
        parts.append(UNICODE_TO_BIJOY.get(cl.pre_kar, cl.pre_kar))
    parts.append(body)
    if cl.reph:
        parts.append(UNICODE_TO_BIJOY["র্"])
    if post_kar:
        parts.append(UNICODE_TO_BIJOY.get(post_kar, post_kar))
    for s in cl.signs:
        parts.append(UNICODE_TO_BIJOY.get(s, s))
    return "".join(parts)


