def unicode_to_bijoy(text: str) -> str:
    """
    ইউনিকোড বাংলা → বিজয় (SutonnyMJ) ASCII।

    ফল সরাসরি SutonnyMJ ফন্টে বসাইলে সঠিক বাংলা দেখাইবে।

    ★ ইংরেজি অক্ষর ও সংখ্যা অপরিবর্তিত থাকে — কিন্তু উহা SutonnyMJ
      রানে রাখিবেন না। `split_runs()` দিয়া পৃথক করুন।
    """
    if not text:
        return text

    text = compose_nukta(text)
    out = []
    for tok in _tokenize(text):
        if isinstance(tok, str):
            out.append(UNICODE_TO_BIJOY.get(tok, tok))
        else:
            out.append(_render(tok))
    return "".join(out)


def to_bijoy_runs(text: str) -> list[tuple[str, str]]:
    """
    প্রতিবেদন লিখিবার জন্য প্রস্তুত খণ্ড-তালিকা —

        [("bn",  "wbix¶v"),        ← SutonnyMJ ফন্টে বসিবে
         ("other", " (Module 1)")]  ← ইংরেজি ফন্টে বসিবে

    ইহাই বিকৃতি ঠেকাইবার একমাত্র নির্ভরযোগ্য উপায়।
    """
    return [
        (kind, unicode_to_bijoy(seg) if kind == "bn" else seg)
        for kind, seg in split_runs(text)
    ]


