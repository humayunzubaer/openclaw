def build_font_proof(scheme: FontScheme, out_path: str | Path) -> Path:
    """একটি ফন্ট-বিন্যাসের যাচাই-নথি তৈরি করে"""
    d = ReportDocument(scheme)
    d.title("ফন্ট যাচাই-নথি", f"বিন্যাস: {scheme.label}")
    d.para(scheme.note, justify=False)
    d.spacer()
    d.para(
        "নিচের প্রতিটি সারি আপনার কম্পিউটারে সঠিক বাংলায় দেখাইতেছে কি না "
        "মিলাইয়া লউন। বাঁ পাশে কী পরীক্ষা করা হইতেছে তাহা লেখা আছে, "
        "ডান পাশে নমুনা লেখা। কোথাও বিকৃতি চোখে পড়িলে কেবল সেই সারির "
        "নামটি জানাইলেই সংশোধন করিয়া দেওয়া যাইবে।"
    )
    d.spacer()
    d.table(["যে গঠনটি পরীক্ষা হইতেছে", "নমুনা লেখা"],
            [[a, b] for a, b in PROOF_CASES])
    d.spacer()

    d.heading("লেখা বিকৃত দেখাইলে যাহা দেখিবেন")
    d.numbered([
        f"“{scheme.bangla_font}” ফন্টটি কম্পিউটারে ইনস্টল করা আছে কি না।",
        f"সম্পূর্ণ নথি নির্বাচন করিয়া ফন্ট “{scheme.bangla_font}” "
        "বসাইয়া দেখুন — তাহাতে ঠিক হইলে ফন্ট-নির্বাচনের সমস্যা।",
        "ইংরেজি অংশ (H.S. Code, KG) ইংরেজি ফন্টেই আছে — ইহা "
        "ইচ্ছাকৃত। বিজয় ফন্টে ইংরেজি অক্ষরই বাংলা গ্লিফ, তাই "
        "উহাদের পৃথক রাখা ছাড়া উপায় নাই।",
    ])
    if scheme.convert_to_bijoy:
        d.spacer()
        d.heading("একটি জানা সীমা")
        d.para(
            "“ক্ষ্ম” ও “ক্ষ্ণ” যুক্তাক্ষরের একটি বিজয় সংকেত লইয়া দুইটি "
            "স্বাধীন উৎস দ্বিমত পোষণ করে। ভুল অক্ষর দেখাইবার ঝুঁকি না "
            "লইয়া উহা ভাঙিয়া লেখা হয়। ফলে “সূক্ষ্ম” সঠিক দেখাইবে, তবে "
            "“তীক্ষ্ণ”-এ হসন্তটি দৃশ্যমান থাকিতে পারে। অক্ষর ভুল হইবে না।"
        )
    return d.save(out_path)


