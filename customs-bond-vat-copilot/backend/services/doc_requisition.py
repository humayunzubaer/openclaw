_BN = str.maketrans("0123456789", "০১২৩৪৫৬৭৮৯")


def _bn(x) -> str:
    return str(x).translate(_BN)


def _bn_date(d: Optional[date]) -> str:
    return d.strftime("%d-%m-%Y").translate(_BN) if d else "—"


def render_requisition(req: Requisition, show_legal: bool = True) -> str:
    """চাহিদাপত্র — প্রমিত চলিত ভাষায়, দাপ্তরিক রীতিতে"""
    L: list[str] = []
    L.append("দলিলাদি দাখিলের চাহিদাপত্র")
    L.append("")
    L.append(f"প্রতিষ্ঠানের ধরন : {req.entity_label}")
    if req.company_name:
        L.append(f"প্রতিষ্ঠানের নাম : {req.company_name}")
    if req.bond_license:
        L.append(f"ওয়্যারহাউস লাইসেন্স নং : {req.bond_license}")
    if req.period_from and req.period_to:
        L.append(
            f"নিরীক্ষা মেয়াদ : {_bn_date(req.period_from)} খ্রিঃ থেকে "
            f"{_bn_date(req.period_to)} খ্রিঃ"
        )
    if req.audit_ref:
        L.append(f"নিরীক্ষা সূত্র : {req.audit_ref}")
    L.append("")
    try:
        from knowledge.report_style import number_to_bangla_words as _w
        words = _w(len(req.documents))
    except Exception:
        words = ""
    L.append(
        f"উপর্যুক্ত মেয়াদের বার্ষিক নিরীক্ষা সম্পাদনের লক্ষ্যে নিম্নবর্ণিত "
        f"{_bn(len(req.documents))}"
        + (f" ({words})" if words else "")
        + " প্রকার দলিলাদি দাখিলের জন্য অনুরোধ করা হলো:"
    )
    L.append("")

    for cat in CATEGORY_ORDER:
        items = [d for d in req.documents if d.category == cat]
        if not items:
            continue
        L.append(f"【{cat}】")
        for d in items:
            star = "" if d.mandatory else "  (প্রযোজ্য ক্ষেত্রে)"
            L.append(f"  {_bn(d.serial)}। {d.name}{star}")
            if d.purpose:
                L.append(f"       উদ্দেশ্য: {d.purpose}")
            if show_legal and d.legal_ref:
                L.append(f"       আইনি ভিত্তি: {d.legal_ref}")
            if d.note:
                L.append(f"       ★ {d.note}")
        L.append("")

    if req.schedules:
        L.append("【প্রযোজ্য তফসিল-ছক】")
        for i, sf in enumerate(req.schedules, start=1):
            tail = "" if sf.status == SCHEDULE_STATUS_APPLIES else f"  ({sf.status})"
            L.append(f"  {_bn(i)}। {sf.render()}{tail}")
            meta = []
            if sf.kind:
                meta.append(sf.kind)
            if sf.columns:
                meta.append(f"{_bn(sf.columns)} কলাম")
            if sf.annual_return:
                meta.append("বার্ষিক নিরীক্ষায় দাখিলযোগ্য")
            if meta:
                L.append("       ধরন: " + " · ".join(meta))
            if show_legal and sf.sro:
                L.append(f"       আইনি ভিত্তি: {sf.sro}")
            if sf.note:
                L.append(f"       ★ {sf.note}")
        L.append("")

    if req.notes:
        L.append("বিশেষ দ্রষ্টব্য:")
        for n in req.notes:
            L.append(f"  ▸ {n}")
        L.append("")

    L.append(
        "উল্লিখিত দলিলাদির অতিরিক্ত ব্যবসা ও নিরীক্ষা সংশ্লিষ্ট অন্য যেকোনো "
        "দলিল প্রয়োজনে তলব করা হতে পারে।"
    )
    return "\n".join(L)


