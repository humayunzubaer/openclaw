@dataclass
class DocumentItem:
    """চাহিত একটি দলিল"""
    serial: str = ""
    name: str = ""
    purpose: str = ""              # কোন কলাম/যাচাইয়ে লাগবে
    legal_ref: str = ""
    mandatory: bool = True
    certainty: str = "V"
    note: str = ""
    category: str = ""

    def render(self) -> str:
        star = "" if self.mandatory else " (প্রযোজ্য ক্ষেত্রে)"
        out = f"{self.name}{star}"
        if self.purpose:
            out += f" — {self.purpose}"
        return out


